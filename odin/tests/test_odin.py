class TestRedaction(FixtureCase):

    def setUp(self):
        super().setUp()
        write(self.repo / "config.py", 'AWS_KEY = "%s"\n' % PLANTED_SECRET)
        write(self.repo / ".env", "API_SECRET=%s\n" % PLANTED_ENV_SECRET)

    def test_planted_secrets_are_detected(self):
        self.init()
        run_odin("inventory", artifacts=self.artifacts)
        code, out = run_odin("secrets", artifacts=self.artifacts)
        self.assertGreaterEqual(out["findings_total"], 2, out)
        report = json.loads((self.packet / "security" / "secrets-redacted.json").read_text(encoding="utf-8"))
        paths = {f["path"] for f in report["findings"]}
        self.assertIn("config.py", paths)
        self.assertIn(".env", paths)

    def test_no_secret_value_appears_anywhere_in_the_packet(self):
        self.init()
        for cmd in ("env", "inventory", "todos", "secrets", "docstub"):
            run_odin(cmd, artifacts=self.artifacts)
        leaked = []
        for path in self.packet.rglob("*"):
            if not path.is_file():
                continue
            blob = path.read_bytes()
            for secret in (PLANTED_SECRET, PLANTED_ENV_SECRET):
                if secret.encode() in blob:
                    leaked.append((path.relative_to(self.packet).as_posix(), secret))
        self.assertEqual(leaked, [], "secret values leaked into the packet: %r" % leaked)

    def test_findings_record_redaction_not_values(self):
        self.init()
        run_odin("inventory", artifacts=self.artifacts)
        run_odin("secrets", artifacts=self.artifacts)
        report = json.loads((self.packet / "security" / "secrets-redacted.json").read_text(encoding="utf-8"))
        for finding in report["findings"]:
            self.assertEqual(finding["value"], "<REDACTED>")
            self.assertIn("fingerprint_sha256_16", finding)
            self.assertIn("not validated", finding["validation"])

    def test_fingerprints_are_stable_and_not_reversible(self):
        a = common.fingerprint(PLANTED_SECRET)
        b = common.fingerprint(PLANTED_SECRET)
        self.assertEqual(a, b, "fingerprints must be stable for deduplication")
        self.assertEqual(len(a), 16)
        self.assertNotIn(PLANTED_SECRET.lower(), a.lower())

    def test_packet_leak_audit_catches_a_planted_value(self):
        self.init()
        run_odin("inventory", artifacts=self.artifacts)
        run_odin("secrets", artifacts=self.artifacts)
        (self.packet / "tool-output" / "leak.log").parent.mkdir(parents=True, exist_ok=True)
        write(self.packet / "tool-output" / "leak.log", "accidentally logged %s\n" % PLANTED_SECRET)
        from odin_lib import scan
        state = common.State.load(str(self.artifacts))
        hits = scan.audit_packet_for_leaks(state)
        self.assertTrue(any(h["packet_path"] == "tool-output/leak.log" for h in hits),
                        "the packet leak audit must catch a value written into the packet")

    def test_example_files_are_not_flagged_as_active(self):
        write(self.repo / ".env.example", "API_SECRET=changeme\n")
        self.init()
        run_odin("inventory", artifacts=self.artifacts)
        run_odin("secrets", artifacts=self.artifacts)
        report = json.loads((self.packet / "security" / "secrets-redacted.json").read_text(encoding="utf-8"))
        for finding in report["findings"]:
            if finding["path"] == ".env.example":
                self.assertNotEqual(finding["status"], "active-looking")


