class TestArchiveInspection(unittest.TestCase):

    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp(prefix="odin-arc-"))

    def tearDown(self):
        shutil.rmtree(self.tmp, ignore_errors=True)

    def test_zip_member_table_is_read_without_extraction(self):
        target = self.tmp / "sample.zip"
        with zipfile.ZipFile(target, "w") as z:
            z.writestr("a.txt", "alpha")
            z.writestr("dir/b.txt", "beta")
        report = archives.inspect(target, "zip", "sample.zip")
        self.assertEqual(report["status"], "inspected")
        self.assertFalse(report["extracted"])
        self.assertEqual(report["counts"]["members"], 2)
        self.assertEqual({m["name"] for m in report["members"]}, {"a.txt", "dir/b.txt"})
        # nothing was written next to the archive
        self.assertEqual(sorted(p.name for p in self.tmp.iterdir()), ["sample.zip"])

    def test_path_traversal_member_is_detected(self):
        target = self.tmp / "evil.zip"
        with zipfile.ZipFile(target, "w") as z:
            z.writestr("../../etc/passwd", "x")
            z.writestr("ok.txt", "y")
        report = archives.inspect(target, "zip", "evil.zip")
        self.assertEqual(report["counts"]["traversing_paths"], 1)
        self.assertIn("path-traversal", [f["kind"] for f in report["findings"]])

    def test_absolute_path_member_is_detected(self):
        target = self.tmp / "abs.zip"
        with zipfile.ZipFile(target, "w") as z:
            z.writestr("/etc/shadow", "x")
        report = archives.inspect(target, "zip", "abs.zip")
        self.assertEqual(report["counts"]["traversing_paths"], 1)

    def test_symlink_escape_in_tar_is_detected(self):
        target = self.tmp / "link.tar"
        with tarfile.open(target, "w") as t:
            info = tarfile.TarInfo("inner/link")
            info.type = tarfile.SYMTYPE
            info.linkname = "../../../../etc/passwd"
            t.addfile(info)
        report = archives.inspect(target, "tar", "link.tar")
        self.assertEqual(report["counts"]["escaping_links"], 1)
        self.assertIn("symlink-escape", [f["kind"] for f in report["findings"]])

    def test_benign_relative_symlink_is_not_flagged(self):
        target = self.tmp / "ok.tar"
        with tarfile.open(target, "w") as t:
            info = tarfile.TarInfo("dir/link")
            info.type = tarfile.SYMTYPE
            info.linkname = "target.txt"
            t.addfile(info)
        report = archives.inspect(target, "tar", "ok.tar")
        self.assertEqual(report["counts"]["escaping_links"], 0)

    def test_decompression_bomb_ratio_is_flagged(self):
        target = self.tmp / "bomb.zip"
        with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
            z.writestr("big.txt", "A" * 5_000_000)
        report = archives.inspect(target, "zip", "bomb.zip")
        kinds = [f["kind"] for f in report["findings"]]
        self.assertIn("decompression-bomb-candidate", kinds)

    def test_nested_archive_is_flagged_and_not_opened(self):
        inner = io.BytesIO()
