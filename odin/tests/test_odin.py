class TestPackaging(FixtureCase):

    def _complete_packet(self):
        """Fill the packet enough that validation passes."""
        self.init()
        run_odin("inventory", artifacts=self.artifacts)
        run_odin("secrets", artifacts=self.artifacts)
        run_odin("docstub", artifacts=self.artifacts)
        P = self.packet
        for doc in common.REQUIRED_TOP_LEVEL_DOCS:
            if doc.endswith(".json"):
                continue
            write(P / doc, "# %s\n\nfixture\n" % doc)
        from odin_lib.verify import REQUIRED_PACKET_ARTIFACTS
        for rel in REQUIRED_PACKET_ARTIFACTS:
            target = P / rel
            if target.exists():
                continue
            target.parent.mkdir(parents=True, exist_ok=True)
            if rel.endswith(".mmd"):
                write(target, "graph TD\n  A --> B\n")
            elif rel.endswith(".jsonl"):
                write(target, '{"fixture": true}\n')
            elif rel.endswith((".json", ".sarif")):
                write(target, '{"fixture": true}\n')
            else:
                write(target, "# fixture\n")
        write(P / "tests" / "coverage-summary.json", '{"measured": false, "reason": "fixture"}\n')
        write(P / "inventory" / "modules.json", '{"modules": []}\n')
        # complete every stub
        for md in (P / "files").rglob("*.md"):
            text = md.read_text(encoding="utf-8")
            write(md, text.replace("<!-- odin:pending -->", "").replace("PENDING", "documented"))
        return P

    def test_packaging_the_same_content_twice_is_byte_identical(self):
        self._complete_packet()
        run_odin("verify", artifacts=self.artifacts)
        run_odin("validate", artifacts=self.artifacts)
        code, first = run_odin("package", artifacts=self.artifacts)
        self.assertEqual(first["status"], "PASS", first)
        code, second = run_odin("package", artifacts=self.artifacts)
        self.assertEqual(first["zip_sha256"], second["zip_sha256"],
                         "repackaging identical content must be byte-identical")

    def test_archive_members_carry_fixed_timestamps_and_modes(self):
        self._complete_packet()
        run_odin("verify", artifacts=self.artifacts)
        run_odin("validate", artifacts=self.artifacts)
        run_odin("package", artifacts=self.artifacts)
        with zipfile.ZipFile(self.artifacts / "findings.zip") as z:
            infos = z.infolist()
            self.assertTrue(infos)
            for info in infos:
                self.assertEqual(info.date_time, (1980, 1, 1, 0, 0, 0), info.filename)
            names = z.namelist()
            self.assertEqual(names, sorted(names, key=lambda n: n.encode("utf-8")),
                             "archive members must be in bytewise-sorted order")

    def test_manifest_covers_every_packet_file_except_itself(self):
        P = self._complete_packet()
        code, out = run_odin("manifest", artifacts=self.artifacts)
        self.assertEqual(out["verification"]["status"], "PASS", out)
        listed = {line.split("  ", 1)[1] for line in
                  (P / "MANIFEST.sha256").read_text(encoding="utf-8").splitlines() if line.strip()}
        self.assertNotIn("MANIFEST.sha256", listed)

    def test_manifest_verification_fails_when_a_file_changes(self):
        P = self._complete_packet()
        run_odin("manifest", artifacts=self.artifacts)
        write(P / "README.md", "# tampered\n")
        from odin_lib import package as packaging
        state = common.State.load(str(self.artifacts))
        result = packaging.verify_manifest(state)
        self.assertEqual(result["status"], "FAIL")
        self.assertIn("README.md", result["digest_mismatch"])


