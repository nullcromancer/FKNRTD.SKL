class TestReadmeLint(unittest.TestCase):

    """The formatting constraints exist because they break real renderers."""

    EMOJI = chr(0x1F680)
    BOX_DRAWING = [chr(0x2500), chr(0x2514), chr(0x251C)]
    ARROW = chr(0x2192)
    GEOMETRIC = chr(0x25A0)
    TECHNICAL = chr(0x23F0)

    def test_a_conforming_readme_passes(self):
        report = readme.lint(GOOD_README)
        self.assertEqual(report["status"], "PASS", report["violations"])

    def test_emoji_in_heading_is_an_error(self):
        body = "## " + self.EMOJI + " Getting Started" + chr(10)
        report = readme.lint(body, require_sections=False)
        self.assertEqual(report["status"], "FAIL")
        self.assertIn("emoji-in-heading", [v["rule"] for v in report["violations"]])

    def test_emoji_shortcode_in_heading_is_an_error(self):
        report = readme.lint("## :rocket: Getting Started" + chr(10),
                             require_sections=False)
        self.assertIn("emoji-shortcode-in-heading",
                      [v["rule"] for v in report["violations"]])

    def test_ampersand_in_heading_is_an_error(self):
        report = readme.lint("## Tech Stack & Dependencies" + chr(10),
                             require_sections=False)
        self.assertEqual(report["status"], "FAIL")
        self.assertIn("ampersand-in-heading", [v["rule"] for v in report["violations"]])

    def test_em_and_en_dash_are_rejected(self):
        for ch in (chr(0x2014), chr(0x2013)):
            report = readme.lint("Human prose " + ch + " nope" + chr(10),
                                 require_sections=False)
            self.assertIn("prose-dash", [v["rule"] for v in report["violations"]])

    def test_box_drawing_characters_are_rejected(self):
        for ch in self.BOX_DRAWING:
            report = readme.lint("text " + ch + " more" + chr(10),
                                 require_sections=False)
            self.assertIn("forbidden-unicode", [v["rule"] for v in report["violations"]],
                          "box-drawing U+%04X must be rejected" % ord(ch))

    def test_arrow_characters_are_rejected(self):
        report = readme.lint("A " + self.ARROW + " B" + chr(10), require_sections=False)
        self.assertIn("forbidden-unicode", [v["rule"] for v in report["violations"]])

    def test_geometric_and_technical_ranges_are_rejected(self):
        for ch in (self.GEOMETRIC, self.TECHNICAL):
            report = readme.lint("x " + ch + chr(10), require_sections=False)
            self.assertIn("forbidden-unicode", [v["rule"] for v in report["violations"]],
                          "U+%04X must be rejected" % ord(ch))

    def test_forbidden_unicode_is_caught_inside_code_fences(self):
        body = "```" + chr(10) + "src " + chr(0x2514) + chr(0x2500) + " file" + chr(10) + "```" + chr(10)
        report = readme.lint(body, require_sections=False)
        self.assertIn("forbidden-unicode", [v["rule"] for v in report["violations"]],
                      "a fenced block is still rendered; it must be checked too")

    def test_ascii_replacements_are_accepted(self):
        body = chr(10).join([
            "A --> B", "", "+------+", "| box  |", "+------+", "",
            "  - dir/", "    - file.cs", ""])
        report = readme.lint(body, require_sections=False)
        self.assertEqual(report["status"], "PASS", report["violations"])

    def test_broken_toc_anchor_is_an_error(self):
        body = chr(10).join(["## Getting Started", "", "- [Nope](#does-not-exist)", ""])
        report = readme.lint(body, require_sections=False)
        self.assertIn("broken-toc-anchor", [v["rule"] for v in report["violations"]])

    def test_valid_toc_anchor_resolves(self):
        body = chr(10).join(["## Getting Started", "", "- [Go](#getting-started)", ""])
        report = readme.lint(body, require_sections=False)
        self.assertNotIn("broken-toc-anchor", [v["rule"] for v in report["violations"]])

    def test_toc_anchor_slugs_match_github_rules(self):
        self.assertEqual(readme.slugify("Getting Started (Local Development)"),
                         "getting-started-local-development")
        self.assertEqual(readme.slugify("Tech Stack and Dependencies"),
                         "tech-stack-and-dependencies")
        self.assertEqual(readme.slugify("Deployment and CI/CD"), "deployment-and-cicd")

    def test_missing_required_sections_are_reported(self):
        report = readme.lint("# Title" + chr(10) + chr(10) + "## Overview" + chr(10))
        self.assertEqual(report["status"], "FAIL")
        self.assertIn("The Rundown", report["missing_required_sections"])

    def test_rundown_must_come_first(self):
        body = GOOD_README.replace("## The Rundown", "## Zzz Later", 1)
        body += chr(10) + "## The Rundown" + chr(10) + chr(10) + "- late" + chr(10)
        report = readme.lint(body)
        self.assertIn("section-order", [v["rule"] for v in report["violations"]])


