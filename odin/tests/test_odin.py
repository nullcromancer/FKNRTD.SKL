class TestNonModification(FixtureCase):

    def test_full_run_leaves_the_repository_byte_identical(self):
        before = self.tree_hashes(self.repo)
        self.init()
        for cmd in ("env", "inventory", "todos", "secrets", "docstub"):
            code, out = run_odin(cmd, artifacts=self.artifacts)
            self.assertEqual(code, 0, (cmd, out))
        after = self.tree_hashes(self.repo)
        self.assertEqual(before, after,
                         "REPO_ROOT changed during analysis; it is evidence and must not be modified")

    def test_verify_reports_pass_on_an_untouched_repository(self):
        self.init()
        run_odin("inventory", artifacts=self.artifacts)
        code, out = run_odin("verify", artifacts=self.artifacts)
        self.assertEqual(code, 0, out)
        self.assertEqual(out["status"], "PASS", out)
        self.assertTrue(out["repository_unchanged"])

    def test_verify_detects_a_modified_file(self):
        self.init()
        run_odin("inventory", artifacts=self.artifacts)
        write(self.repo / "README.md", "# Fixture, tampered\n")
        code, out = run_odin("verify", artifacts=self.artifacts)
        self.assertEqual(out["status"], "FAIL", out)
        self.assertEqual(out["severity"], "critical-process-failure")
        self.assertIn("README.md", [m["path"] for m in out["content_modified"]])

    def test_verify_detects_an_added_and_a_removed_file(self):
        self.init()
        run_odin("inventory", artifacts=self.artifacts)
        write(self.repo / "NEW.txt", "new\n")
        (self.repo / "README.md").unlink()
        code, out = run_odin("verify", artifacts=self.artifacts)
        self.assertEqual(out["status"], "FAIL")
        self.assertIn("NEW.txt", out["added"])
        self.assertIn("README.md", out["removed"])

    def test_toolkit_writes_no_bytecode_into_the_repository(self):
        """The toolkit may live inside the repository it analyses.

        Importing odin_lib would normally drop __pycache__ next to the source,
        which the protocol forbids: caches must never be written into REPO_ROOT.
        """
        toolkit = self.repo / "vendored-skill" / "scripts"
        toolkit.parent.mkdir(parents=True, exist_ok=True)
        shutil.copytree(SCRIPTS, toolkit)
        for stale in toolkit.rglob("__pycache__"):
            shutil.rmtree(stale, ignore_errors=True)

        artifacts = self.tmp / "artifacts-vendored"
        proc = subprocess.run(
            [sys.executable, str(toolkit / "odin.py"), "init",
             "--repo", str(self.repo), "--artifacts", str(artifacts)],
            capture_output=True, text=True, timeout=300)
        self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)

        polluted = sorted(str(p.relative_to(self.repo).as_posix())
                          for p in self.repo.rglob("__pycache__"))
        self.assertEqual(polluted, [],
                         "the toolkit wrote bytecode caches into REPO_ROOT: %r" % polluted)

    def test_artifact_root_inside_the_repository_is_refused(self):
        code, out = run_odin("init", "--repo", str(self.repo),
                             "--artifacts", str(self.repo / "findings-out"))
        self.assertNotEqual(code, 0)
        self.assertIn("outside REPO_ROOT", out.get("error", ""))
        self.assertFalse((self.repo / "findings-out").exists(),
                         "a refused init must not leave anything behind in REPO_ROOT")


