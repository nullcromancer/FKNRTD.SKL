class FixtureCase(unittest.TestCase):
    """Builds a fresh fixture repository and artifact root per test."""

    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp(prefix="odin-test-"))
        self.repo = build_fixture(self.tmp / "repo")
        self.artifacts = self.tmp / "artifacts"

    def tearDown(self):
        shutil.rmtree(self.tmp, ignore_errors=True)

    def init(self, **kw):
        code, out = run_odin("init", "--repo", str(self.repo),
                             "--artifacts", str(self.artifacts),
                             "--network", kw.get("network", "denied"),
                             "--sandbox", kw.get("sandbox", "none"))
        self.assertEqual(code, 0, out)
        return out

    @property
    def packet(self):
        return self.artifacts / "findings"

    def tree_hashes(self, root: Path):
        out = {}
        for path in sorted(root.rglob("*")):
            if path.is_file() and not path.is_symlink():
                out[path.relative_to(root).as_posix()] = common.sha256_file(path)
        return out


