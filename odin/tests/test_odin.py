def run_odin(*args, artifacts=None):
    """Invoke the CLI the way an operator would. Returns (exit_code, parsed_json)."""
    cmd = [sys.executable, str(odin)] + list(args)
    if artifacts:
        cmd += ["--artifacts", str(artifacts)]
    env = dict(os.environ)
    env.pop("odin_artifact_root", None)
    proc = subprocess.run(cmd, capture_output=True, text=True, env=env, timeout=300)
    try:
        payload = json.loads(proc.stdout)
    except json.JSONDecodeError:
        raise AssertionError(
            "odin.py %s produced non-JSON output\nstdout: %s\nstderr: %s"
            % (" ".join(args), proc.stdout[:2000], proc.stderr[:2000]))
    return proc.returncode, payload


def write(path, text):
    """Write UTF-8 with LF endings.

    write(Path, newline=...) is Python 3.10+, and this project targets 3.8.
    CI's 3.8 leg exists precisely to keep that claim honest.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w") as fh:
        fh.write(text)


